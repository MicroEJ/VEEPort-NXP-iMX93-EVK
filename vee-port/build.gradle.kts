import com.microej.gradle.tasks.BuildVeePortConfigurationTask
import com.microej.gradle.tasks.BuildVeePortTask
import java.io.FileOutputStream
import java.util.Properties
import javax.xml.parsers.DocumentBuilderFactory
import javax.xml.transform.TransformerFactory
import javax.xml.transform.dom.DOMSource
import javax.xml.transform.stream.StreamResult

plugins {
    id("com.microej.gradle.veeport") version libs.versions.microej.sdk
}

configurations {
    create("compileClasspath")
}

microej {
    skippedCheckers = "changelog,readme,license"
    withIvyDescriptor()
}

// One switch drives the rio pack and the BUILD_RIO CMake option.
val rioEnabled = providers.gradleProperty("experimental.rio.enabled").orNull.toBoolean()

dependencies {
    microejArchitecture(libs.architecture)

    microejPack(libs.pack.ui.architecture)

    // Packs are fetched from linux-abstraction-layer/gradle/libs.versions.toml
    microejPack(libsOverride.api.device)
    microejPack(libsOverride.pack.ecom.network)
    microejPack(libsOverride.api.event)
    microejPack(libsOverride.pack.fs)
    microejPack(libsOverride.pack.net)
    // rio is experimental: see README.md, "Experimental Features".
    if (rioEnabled) {
        microejPack(libsOverride.lib.rio)
    }
    microejPack(libsOverride.api.crypto)

    microejFrontPanel(project(":vee-port:front-panel"))

    microejMock(libs.jenkins)
}

val bspScriptsDir = run {
    val properties = Properties().apply {
        layout.projectDirectory.file("configuration.properties").asFile.inputStream().use { load(it) }
    }
    val bspRootDir = properties.getProperty("bsp.root.dir").replace("\${project.parent.dir}", "..")
    file("$bspRootDir/${properties.getProperty("bsp.microejscript.relative.dir")}")
}

tasks {
    val copyBspScripts by registering(Copy::class) {
        from("bsp")
        into(bspScriptsDir)
        // Carry the Gradle property over to CMake, so one switch drives both the
        // rio pack and the abstraction layer that implements it.
        val scriptsDir = bspScriptsDir
        val rio = rioEnabled
        // Without this the copy stays up-to-date when only the property changes,
        // and the generated file keeps its previous value.
        inputs.property("rioEnabled", rio)
        outputs.file(File(scriptsDir, "gradle_options.cmake"))
        doLast {
            File(scriptsDir, "gradle_options.cmake").writeText(
                "# Generated by :vee-port:copyBspScripts. Do not edit.\n" +
                    "set(BUILD_RIO ${if (rio) "ON" else "OFF"})\n"
            )
        }
    }

    withType<BuildVeePortTask>().configureEach { dependsOn(copyBspScripts) }
    withType<BuildVeePortConfigurationTask>().configureEach { dependsOn(copyBspScripts) }

    // Remove the C build outputs by delegating to the BSP clean script,
    // the single source of truth for what gets deleted
    val cleanBsp by registering(Exec::class) {
        val scriptsDir = bspScriptsDir
        val isWindows = System.getProperty("os.name").lowercase().contains("windows")
        val cleanScript = scriptsDir.resolve(if (isWindows) "clean.bat" else "clean.sh")
        // No-op when the submodule is not initialized
        onlyIf { cleanScript.exists() }
        workingDir(scriptsDir)
        if (isWindows) {
            commandLine("cmd", "/c", cleanScript.absolutePath)
        } else {
            commandLine("bash", cleanScript.absolutePath)
        }
    }

    named("clean") { dependsOn(cleanBsp) }

    val updateIvyDescriptor by registering {
        doLast {
            val ivyFile = layout.buildDirectory.file("ivy.xml").get().asFile.absolutePath

            val factory = DocumentBuilderFactory.newInstance()
            val builder = factory.newDocumentBuilder()
            val document = builder.parse(ivyFile)
            val publicationsElements = document.getElementsByTagName("publications")
            if (publicationsElements.length == 1) {
                val publications = publicationsElements.item(0)

                while (publications.hasChildNodes()) {
                    publications.removeChild(publications.firstChild)
                }

                var newPublication = document.createElement("artifact")
                newPublication.setAttribute("name", "vee-port")
                newPublication.setAttribute("type", "zip")
                newPublication.setAttribute("ext", "zip")
                newPublication.setAttribute("conf", "default")
                publications.appendChild(newPublication)

                newPublication = document.createElement("artifact")
                newPublication.setAttribute("name", "vee-port")
                newPublication.setAttribute("type", "pom")
                newPublication.setAttribute("ext", "pom")
                newPublication.setAttribute("conf", "dist")
                publications.appendChild(newPublication)

                newPublication = document.createElement("artifact")
                newPublication.setAttribute("name", "vee-port")
                newPublication.setAttribute("type", "module")
                newPublication.setAttribute("ext", "module")
                newPublication.setAttribute("conf", "dist")
                publications.appendChild(newPublication)

                val transformerFactory = TransformerFactory.newInstance()
                val transformer = transformerFactory.newTransformer()
                val source = DOMSource(document)
                val result = StreamResult(FileOutputStream(ivyFile))
                transformer.transform(source, result)
            }
        }
    }

    named("generateIvyDescriptor") { finalizedBy(updateIvyDescriptor) }
}

artifacts {
    add("additionalElements", file("../README.md")) {
        classifier = "readme"
    }
    add("additionalElements", file("../CHANGELOG.md")) {
        classifier = "changelog"
    }
    add("additionalElements", file("../LICENSE.txt")) {
        classifier = "license"
    }
    add("additionalElements", file("../NOTICE.txt")) {
        classifier = "notice"
    }
}
